"""Who-said-what checks for the newsroom writer, on sentences two reviewers flagged on 2026-10-28.

Each Vietnamese sentence is the writer's published text from cycle 20261027T181044Z; each English paragraph is the
source sentence the reviewers quoted against it.
"""

import unittest

from radar.summary_validation import attribution_error, entity_error

OPERA = ("That doesn't eliminate every privacy risk, but it does give users a bit more control.", "TechCrunch")
OPERA_SAYS = ("There's the additional advantage of privacy, the company said.", "TechCrunch")
INSIDERS = ("Accordingly, the company has put most of its AI models on ice, Amazon insiders told Bloomberg.",
            "Futurism")
ROBOTS = ("At the time Abbeel joined the tech giant, Covariant's founders were working on AI models for robots, "
          "which lines up pretty well with Amazon's push to automate everything it possibly can.", "Futurism")
ORG = ("ORG found that the percentage of summaries generated by the ACS deemed not fit for use—often because they "
       "contain factual errors or misrepresentations—is significantly higher than the published 9 percent error "
       "rate calculated in the pilot evaluation.", "WIRED")
APPLE = ("The assistant, which is built on AI models from Apple and OpenAI, can understand a document's context to "
         "perform tasks like designing, animating, and refining slides in Keynote.", "The Verge")
NETHERLANDS = ("The Netherlands said it would cut 25,000 government jobs as part of AI-related savings, among the "
               "more aggressive moves yet set out by states seeking to adapt to the technology.", "Semafor")
UAE = ("Others are even more ambitious: The UAE is pushing to become the world's first \"AI-native\" government "
       "in order to maximize productivity from its tiny population.", "Semafor")
NVIDIA = ("Nemotron 3.5 Bolt E4B 4GB offers ~40% higher average quality against the prior model on relevant "
          "benchmarks and outputs up to ~80% fewer tokens versus peers.", "NVIDIA Technical Blog")


class AttributionTests(unittest.TestCase):
    def test_a_remark_in_the_outlets_voice_cannot_be_given_to_the_company(self):
        sentence = ("Theo Opera, dù phương pháp xử lý trên thiết bị tăng khả năng kiểm soát dữ liệu, giải pháp này "
                    "không thể loại trừ mọi rủi ro bảo mật.")
        self.assertEqual(attribution_error(sentence, [OPERA]), "speaker_not_in_source: Opera")
        # Citing a paragraph where Opera speaks does not cover the outlet's own judgement in the same sentence.
        self.assertEqual(attribution_error(sentence, [OPERA_SAYS, OPERA]), "speaker_not_in_source: Opera")
        self.assertIsNone(attribution_error(
            "Theo TechCrunch, cách làm này chưa loại trừ mọi rủi ro về quyền riêng tư nhưng giúp người dùng "
            "kiểm soát dữ liệu nhiều hơn.", [OPERA]))

    def test_insiders_speak_only_for_their_own_paragraph(self):
        sentence = ("Theo nguồn tin nội bộ, các mô hình Nova xử lý văn bản, hình ảnh và video của Amazon chỉ nhận "
                    "tài nguyên tối thiểu dù vẫn được duy trì kỹ thuật, trong khi tài lực được dồn vào dự án AI "
                    "cho robot.")
        self.assertEqual(attribution_error(sentence, [INSIDERS, ROBOTS]),
                         "speaker_not_in_source: nguồn tin nội bộ")
        self.assertIsNone(attribution_error(
            "Theo nguồn tin nội bộ được Bloomberg dẫn, Amazon đã tạm gác phần lớn các mô hình AI của mình.",
            [INSIDERS]))

    def test_an_organisations_finding_is_not_a_general_fact(self):
        sentence = ("Dù ước tính tiết kiệm một giờ mỗi hồ sơ, tỷ lệ tóm tắt không đạt chuẩn trong thực tế cao hơn "
                    "mức lỗi 9% khi thử nghiệm, thậm chí tòa án từng ghi nhận tài liệu do AI ảo giác (tự tạo thông "
                    "tin sai) để bác đơn.")
        # The estimate in the concessive clause does not attribute the finding that follows it.
        self.assertEqual(attribution_error(sentence, [ORG]), "unattributed_judgement")
        self.assertIsNone(attribution_error(
            "Tổ chức ORG phát hiện tỷ lệ tóm tắt không đạt chuẩn cao hơn đáng kể mức lỗi 9% công bố khi thử "
            "nghiệm.", [ORG]))

    def test_a_purpose_the_source_never_states_is_rejected(self):
        self.assertEqual(attribution_error(
            "Hãng xây dựng công cụ này dựa trên các mô hình của Apple và OpenAI nhằm tự động hóa xử lý nội dung.",
            [APPLE]), "unsupported_purpose")
        self.assertEqual(attribution_error(
            "Đợt cắt giảm 25.000 việc làm công chức được đưa ra nhằm tối ưu hóa hiệu quả dịch vụ công.",
            [NETHERLANDS]), "unsupported_purpose")
        self.assertIsNone(attribution_error(
            "Các Tiểu vương quốc Ả Rập Thống nhất muốn trở thành chính phủ lấy AI làm nền tảng đầu tiên nhằm "
            "nâng cao năng suất.", [UAE]))

    def test_round_five_sentences_that_name_their_speaker_correctly_pass(self):
        # Sentences agy wrote on 2026-10-28 that a first version of these rules dropped by mistake.
        filing = ("In its IPO prospectus filed on Monday, the tech giant revealed it is on the hook for about $400 "
                  "billion in chip purchases and data center leases, and lost $81 billion in the first half of this "
                  "year. Rising temperatures and heightened risk from wildfires due to climate change also pose "
                  "physical threats to the company's infrastructure, it warned.", "semafor")
        self.assertIsNone(attribution_error(
            "Theo công bố từ Opera, việc xử lý cục bộ giúp bảo vệ quyền riêng tư do dữ liệu lưu trên thiết bị "
            "cá nhân.", [("There's the additional advantage of privacy, the company said.", "techcrunch")]))
        self.assertIsNone(attribution_error(
            "Anthropic cho biết đang chịu ràng buộc khoảng 400 tỷ USD tiền mua chip và thuê trung tâm dữ liệu.",
            [filing]))
        self.assertIsNone(attribution_error(
            "Bên cạnh nguy cơ tài chính, tài liệu cảnh báo nhiệt độ tăng cao và cháy rừng do biến đổi khí hậu "
            "cũng đang đe dọa hạ tầng kỹ thuật của doanh nghiệp.", [filing]))
        self.assertIsNone(attribution_error(
            "Về độ chính xác, tổ chức ORG nhận thấy tỷ lệ tóm tắt không đạt chuẩn do lỗi thực tế cao hơn đáng kể "
            "so với mức 9% trong thử nghiệm.", [ORG]))
        self.assertIsNone(attribution_error(
            "Lợi nhuận tại các công ty công nghiệp lớn của Trung Quốc đã tăng hơn 15% so với cùng kỳ năm trước "
            "trong chín tháng đầu năm 2026, ghi nhận mức tăng mạnh nhất nhiều tháng qua.",
            [("China's industrial profits grew at their strongest pace in months as AI-related manufacturing "
              "surged, though analysts warned of a growing economic divide.", "semafor")]))

    def test_round_five_sentences_that_still_lose_their_speaker_fail(self):
        self.assertEqual(attribution_error(
            "Giới chuyên gia cho biết mô hình này được thiết kế để hạn chế quyền lực của cổ đông đối với hội đồng "
            "quản trị.",
            [("Experts say it should give Anthropic freedom to pursue profits without letting shareholders force "
              "it to cut corners on safety.", "the verge"),
             ("Another key safeguard aims to protect Anthropic's mission by limiting shareholder influence over one "
              "of the biggest levers of corporate power: the company's board of directors.", "the verge")]),
            "speaker_not_in_source: Giới chuyên gia")
        self.assertEqual(attribution_error(
            "Dù đại diện Bộ Nội vụ khẳng định AI chỉ hỗ trợ tra cứu chứ không tự quyết định, việc các công cụ này "
            "vắng mặt trong danh mục thuật toán công khai của chính phủ vẫn gây nhiều lo ngại về tính minh bạch.",
            [("The potential probe follows lawmakers and researchers publicly questioning the tools' accuracy and "
              "the government's secrecy around their use.", "wired"),
             ("\"They cannot be used in isolation and do not make decisions on claims,\" a Home Office spokesperson "
              "tells WIRED in an email.", "wired")]),
            "unattributed_judgement")

    def test_narration_in_the_outlets_voice_needs_no_speaker(self):
        # Round 5, Semafor on China: the judgement is Semafor's own narration; the expert in the same
        # paragraph is quoted for "hollow growth", which the sentence does not use.
        semafor = ("However, the domestic economy remains a drag: Consumer spending, weighed down by a property "
                   "crisis, remains paltry, while a thin social safety net has turned many into savers. Though "
                   "overall economic output remains within government targets, consumption and investment are "
                   "adding very little, equating to \"hollow growth,\" according to one expert.", "semafor")
        self.assertIsNone(attribution_error(
            "Ở chiều ngược lại, kinh tế nội địa tiếp tục ảm đạm do khủng hoảng bất động sản đè nặng lên chi tiêu "
            "tiêu dùng, đồng thời mạng lưới an sinh xã hội mỏng khiến người dân thắt chặt tiết kiệm.", [semafor]))
        # A clause that shares the quoted finding's figure is that finding, even beside outlet narration.
        wired = ("Researchers are concerned about the accuracy of the AI tools. " + ORG[0], "wired")
        self.assertEqual(attribution_error(
            "Tỷ lệ tóm tắt không đạt chuẩn trong thực tế cao hơn mức lỗi 9% khi thử nghiệm.", [wired]),
            "unattributed_judgement")

    def test_plain_acronyms_are_not_invented_names(self):
        # Round 5, Firefox: "PDF" was dropped as an invented entity although the source says "PDFs".
        evidence = ("This feature currently supports text fields on web forms, but Mozilla is working to add "
                    "support for dropdown menus and PDFs.")
        self.assertIsNone(entity_error(
            "Dù vậy, công cụ hiện mới chỉ hỗ trợ các trường văn bản trên web chứ chưa áp dụng cho danh sách thả "
            "xuống hay tài liệu PDF.", evidence))
        self.assertEqual(entity_error("Công cụ do Mozilla và Qwerty phát triển hỗ trợ tài liệu PDF.", evidence),
                         "invented_entity: Qwerty")

    def test_function_words_and_attributed_figures_pass(self):
        # A company figure it states itself, "để" for a use and "trang web mục tiêu" (target site) are not faults.
        self.assertIsNone(attribution_error(
            "Hãng cho biết mô hình Nemotron 3.5 Bolt E4B 4GB đạt chất lượng trung bình cao hơn khoảng 40% so với "
            "phiên bản trước.", [NVIDIA]))
        self.assertIsNone(attribution_error(
            "Công cụ này cho phép người dùng Firefox tận dụng dữ liệu từ các thẻ đang mở để điền hồ sơ xin việc, "
            "đồng thời nhận thông báo khi trang web mục tiêu có thay đổi hoặc đợt giảm giá mới.",
            [("As an example, Mozilla says Smart Window can pull information from your online portfolio or "
              "LinkedIn page to paste your work history into a job application.", "The Verge")]))


if __name__ == "__main__":
    unittest.main()
